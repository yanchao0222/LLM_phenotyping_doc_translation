    "descendant_t1 AS (\n",
    "  -- Get all descendant_concept_ids for T1 drugs\n",
    "  SELECT descendant_concept_id\n",
    "  FROM victr_sd.sd_omop_prod.concept_ancestor\n",
    "  WHERE ancestor_concept_id IN (SELECT concept_id FROM rxnorm_concepts_t1)\n",
    "),\n",
    "\n",
    "lab_flags AS (\n",
    "  SELECT  m.person_id,\n",
    "          MAX(CASE WHEN lc.concept_code = '1558-6' AND m.value_as_number >= 125 THEN 1 END) AS fast_case,\n",
    "          MAX(CASE WHEN lc.concept_code IN ('2339-0','2345-7') AND m.value_as_number > 200 THEN 1 END) AS rnd_case,\n",
    "          MAX(CASE WHEN lc.concept_code IN ('4548-4','17856-6','4549-2','17855-8') AND m.value_as_number >= 6.5 THEN 1 END) AS a1c_case,\n",
    "          MAX(CASE WHEN lc.concept_code = '1558-6' AND m.value_as_number >= 110 THEN 1 END) AS fast_ctrl,\n",
    "          MAX(CASE WHEN lc.concept_code IN ('2339-0','2345-7') AND m.value_as_number > 110 THEN 1 END) AS rnd_ctrl,\n",
    "          MAX(CASE WHEN lc.concept_code IN ('4548-4','17856-6','4549-2','17855-8') AND m.value_as_number >= 6.0 THEN 1 END) AS a1c_ctrl,\n",
