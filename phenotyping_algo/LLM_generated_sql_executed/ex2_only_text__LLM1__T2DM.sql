    "         WHEN dx_dm_any_cnt > 0                               THEN 0\n",
    "         WHEN rx_t1 = 1 OR rx_t2 = 1                          THEN 0\n",
    "         WHEN dm_supply_flag = 1                              THEN 0\n",
    "         WHEN (fast_ctrl=1 OR rnd_ctrl=1 OR a1c_ctrl=1)       THEN 0\n",
    "         WHEN fam_hist_dm = 1                                 THEN 0\n",
    "         ELSE 1\n",
    "       END  AS is_t2dm_control\n",
    "FROM evidence;"
