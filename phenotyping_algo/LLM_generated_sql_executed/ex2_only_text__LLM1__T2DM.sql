    "CREATE TABLE workspace_sdphenotypecore.phenotype_llm_logic.ex2_only_text_LLM1_T2DM AS \n",
    "\n",
    "WITH loinc_concepts AS (\n",
    "  -- REVISED (was: SELECT * FROM concept WHERE vocabulary_id = 'LOINC')\n",
    "  SELECT concept_id, concept_code\n",
    "  FROM victr_sd.sd_omop_prod.concept\n",
