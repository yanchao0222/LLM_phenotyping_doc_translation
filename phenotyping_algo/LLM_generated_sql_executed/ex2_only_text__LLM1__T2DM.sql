    "          COALESCE(lf.a1c_case,0)         AS a1c_case,\n",
    "          COALESCE(lf.fast_ctrl,0)        AS fast_ctrl,\n",
    "          COALESCE(lf.rnd_ctrl,0)         AS rnd_ctrl,\n",
